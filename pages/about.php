    <section id="História">
        <h3>Nossa História</h3>
        <p>Tudo começou em 2015, em Americana, interior de São Paulo, com uma pergunta simples: <b>quem cuida de quem cuidou de nós?</b></p>
        <p>Um grupo de amigos, moradores do mesmo bairro, percebeu que muitos idosos ao redor viviam em silêncio. Alguns dormiam nas ruas. Outros moravam com filhos que, por falta de tempo ou de condições, não conseguiam acompanhá-los no dia a dia. Eram pessoas que tinham criado famílias, trabalhado a vida inteira e construído a cidade, e que agora eram tratadas como invisíveis.</p>
        <p>Sem sede, sem verba e sem experiência, o grupo começou com o que tinha: tempo e vontade de ajudar. Nas primeiras semanas, eram poucos voluntários visitando casas, levando refeições, fazendo companhia e resolvendo pequenas tarefas. Foi ali que aprendemos a primeira lição da CDQC:<b> muitas vezes, o que o idoso mais precisa é ser ouvido.</b></p>
        <p>Com o passar dos meses, o número de pedidos de ajuda cresceu, e ficou claro que as visitas não bastavam para quem não tinha onde morar. Então nasceu o nosso Centro de Acolhimento, na Avenida Prefeito Doutor José Adilson Basso, em Americana. Ali, além de abrigo, oferecemos um lugar onde cada pessoa é recebida com respeito à sua história de vida.</p>
        <p>Hoje, a CDQC trabalha em duas frentes que se complementam: voluntários que visitam idosos diariamente e um centro de acolhimento para quem precisa de um lar. Já atendemos mais de 1.200 idosos, e cada um deles nos lembrou que envelhecer com dignidade não deveria ser privilégio.</p>
        <p>Acreditamos que esse trabalho só se sustenta com transparência. Por isso, prestamos contas de tudo o que recebemos e gastamos, para que cada doador e cada voluntário saiba exatamente como a sua ajuda se transforma em cuidado.</p>
        <p>Nossa missão continua a mesma do primeiro dia, mas o sonho é maior: uma sociedade que enxergue o envelhecimento com dignidade, autonomia e respeito, e que combata o idadismo em cada esquina.</p>
        <h4><i>Cuide de Quem Cuidou. Porque um dia, foram eles que cuidaram de nós.</i></h4>
        
