    <section id="Principios">
        <h3>Principios</h3>
        <ol>
            <li><b>Escuta ativa:</b> cada idoso é ouvido antes de qualquer decisão sobre o seu cuidado.</li>
            <li><b>Cuidado personalizado:</b> o atendimento respeita a rotina, os gostos e as necessidades individuais, sem tratar todos da mesma forma.</li>
            <li><b>Protagonismo do idoso:</b> quem é cuidado participa das escolhas sobre a própria vida, mesmo nas pequenas.</li>
            <li><b>Convivência entre gerações:</b> estimular o contato entre jovens, adultos e idosos, com troca de experiências.</li>
            <li><b>Voluntariado responsável:</b> voluntários são orientados e acompanhados, para que a ajuda seja segura e constante.</li>
            <li><b>Sigilo e privacidade:</b> dados pessoais e histórias de vida são tratados com confidencialidade (combina com a LGPD que você já documentou).</li>
            <li><b>Acolhimento sem julgamento;</b> ninguém é questionado ou criticado pela situação em que chegou.</li>
            <li><b>Corresponsabilidade familiar:</b> apoiar as famílias, e não substituí-las, incentivando os vínculos afetivos.</li>
            <li><b>Sustentabilidade:</b> usar bem os recursos e buscar parcerias para manter o trabalho a longo prazo.</li>
            <li><b>Melhoria contínua:</b> avaliar e ajustar os serviços a partir do retorno de idosos, famílias e voluntários.</li> 
        </ol>
    </section>
